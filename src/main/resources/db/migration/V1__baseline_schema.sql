-- ─────────────────────────────────────────────────────────────
-- V1: 基础表结构（PostgreSQL / H2(PostgreSQL 模式) 通用 DDL）
-- 说明：表结构由 Flyway 统一管理，Hibernate 仅做 validate 校验。
--      时间列统一使用带时区的 timestamp，对应 Java 侧 java.time.Instant。
-- ─────────────────────────────────────────────────────────────

create table t_user
(
    id          bigint generated by default as identity primary key,
    username    varchar(32)                  not null,
    password    varchar(100)                 not null,
    email       varchar(128),
    phone       varchar(20),
    status      varchar(16)                  not null,
    created_by  varchar(64)                  not null,
    updated_by  varchar(64)                  not null,
    create_time timestamp(6) with time zone  not null,
    update_time timestamp(6) with time zone  not null,
    version     bigint                       not null,
    constraint uk_t_user_username unique (username)
);

comment on table t_user is '用户表';
comment on column t_user.password is 'BCrypt 摘要，禁止存明文';
comment on column t_user.status is 'UserStatus: ACTIVE/DISABLED/LOCKED';

create table t_user_role
(
    user_id bigint      not null,
    role    varchar(32) not null,
    constraint pk_t_user_role primary key (user_id, role),
    constraint fk_t_user_role_user foreign key (user_id) references t_user (id)
);

comment on table t_user_role is '用户角色（@ElementCollection）';

create table t_order
(
    id           bigint generated by default as identity primary key,
    order_no     varchar(32)                  not null,
    user_id      bigint                       not null,
    status       varchar(16)                  not null,
    total_amount numeric(18, 2)               not null,
    remark       varchar(200),
    created_by   varchar(64)                  not null,
    updated_by   varchar(64)                  not null,
    create_time  timestamp(6) with time zone  not null,
    update_time  timestamp(6) with time zone  not null,
    version      bigint                       not null,
    constraint uk_t_order_order_no unique (order_no)
);

comment on table t_order is '订单表；user_id 仅保存标识，不建立外键以保持聚合解耦';
comment on column t_order.status is 'OrderStatus: CREATED/PAID/SHIPPED/COMPLETED/CANCELLED';
comment on column t_order.version is '乐观锁版本号（@Version）';

create table t_order_item
(
    id           bigint generated by default as identity primary key,
    order_id     bigint         not null,
    product_name varchar(64)    not null,
    unit_price   numeric(18, 2) not null,
    quantity     integer        not null,
    constraint fk_t_order_item_order foreign key (order_id) references t_order (id)
);

comment on table t_order_item is '订单明细行，随订单级联保存/删除';

create index idx_t_order_user_id on t_order (user_id);
create index idx_t_order_status on t_order (status);
create index idx_t_order_create_time on t_order (create_time desc);
create index idx_t_order_item_order_id on t_order_item (order_id);
